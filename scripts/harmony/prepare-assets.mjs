import { readFileSync, writeFileSync } from 'node:fs';

const raw = new URL('../../apps/harmony/entry/src/main/resources/rawfile/', import.meta.url);
const { app } = JSON.parse(readFileSync(new URL('../../apps/harmony/AppScope/app.json5', import.meta.url), 'utf8'));
for (const file of ['oh-package.json5', 'entry/oh-package.json5']) {
  const manifest = JSON.parse(readFileSync(new URL('../../apps/harmony/' + file, import.meta.url), 'utf8'));
  if (manifest.version !== app.versionName) throw new Error('Align HarmonyOS manifest versions before building');
}
const metadata = {
  name: 'CloudCLI Harmony', version: app.versionName, versionCode: app.versionCode,
  repository: 'https://github.com/stlin256/claudecodeui',
  issues: 'https://github.com/stlin256/claudecodeui/issues/new/choose',
  maintainer: 'stlin256', profile: 'https://github.com/stlin256',
  avatar: 'data:image/png;base64,' + readFileSync(new URL('maintainer-avatar.png', raw)).toString('base64'),
};
const generated = '/* Generated by scripts/harmony/prepare-assets.mjs from the native manifest. */\n' +
  `window.cloudcliHarmonyApp = Object.freeze(${JSON.stringify(metadata)});\n`;
const destination = new URL('app-info.js', raw);
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8').replaceAll('\r\n', '\n') !== generated) throw new Error('Run node scripts/harmony/prepare-assets.mjs');
} else writeFileSync(destination, generated);
